/** Whole-label overrides, checked before phrase-by-phrase replacement. */
const WHOLE_HI: Record<string, string> = {
  "Active Schemes · திட்டங்கள்": "Active Schemes · योजनाएँ",
};

const TAMIL_RUN = /[஀-௿][஀-௿\s&—–\-0-9()A-Za-z]*[஀-௿)]|[஀-௿]/g;

/** Hindi for a Tamil phrase, falling back to the Tamil when unmapped. */
export function hindiFor(tamil: string): string {
  const key = tamil.replace(/&amp;/g, "&").trim();
  return PHRASE_HI[key] ?? tamil;
}

/**
 * A mixed English/Tamil label in the reader's second language: unchanged for
 * Tamil, each Tamil phrase swapped for its Hindi rendering otherwise.
 */
export function inSecondLang(text: string, l2: SecondLang): string {
  if (l2 === "ta") return text;
  if (WHOLE_HI[text]) return WHOLE_HI[text];
  return text.replace(TAMIL_RUN, (run) => hindiFor(run));
}
